#!/usr/bin/env bash
# trim.sh VERSION EXCHANGE... — rebuild this module from CCXT's Go package at
# VERSION, keeping only the named exchanges.
#
#   ./trim.sh v4.5.77 binance kraken coinbase
#
# It deletes every other exchange's files and drops them from the two
# registries that create an exchange by name; nothing else is edited.
set -euo pipefail

if [ $# -lt 2 ]; then
	echo "usage: $0 VERSION EXCHANGE..." >&2
	exit 2
fi
version=$1
shift
keep=("$@")

here=$(cd "$(dirname "$0")" && pwd)
src=$(cd "$here" && GOFLAGS=-mod=mod go mod download -json "github.com/ccxt/ccxt/go/v4@$version" | python3 -c 'import json,sys; print(json.load(sys.stdin)["Dir"])')

# Start clean: everything generated by a previous run goes.
find "$here" -maxdepth 1 -name '*.go' -delete
rm -rf "$here/protoc" "$here/go.sum"

for f in "$src"/*.go; do
	case "$f" in *_test.go) continue ;; esac
	cp "$f" "$here/"
done
cp -R "$src/protoc" "$here/"
cp "$src/LICENSE" "$here/LICENSE"
cp "$src/go.sum" "$here/go.sum"
chmod -R u+w "$here"

# Every exchange has an <id>_api.go; drop the ones not kept.
for api in "$here"/*_api.go; do
	id=$(basename "$api" _api.go)
	if [[ " ${keep[*]} " != *" $id "* ]]; then
		rm -f "$here/$id.go" "$here/${id}_api.go" "$here/${id}_wrapper.go"
	fi
done

# The two registries list every exchange; keep only the kept ones' cases.
python3 - "$here" "${keep[@]}" <<'PY'
import re, sys
here, keep = sys.argv[1], set(sys.argv[2:])
def trim(path, keep, body_lines):
    s = open(path).read()
    pat = re.compile(r'\tcase "(\w+)":\n(?:\t\t.*\n){%d}' % body_lines)
    s = pat.sub(lambda m: m.group(0) if m.group(1) in keep else '', s)
    open(path, 'w').write(s)
trim(here + '/exchange_dynamic.go', keep | {'Exchange'}, 3)
trim(here + '/exchange_typed_interface.go', keep | {'exchange'}, 2)
PY

# The module keeps CCXT's own path (github.com/ccxt/ccxt/go/v4) and go.mod, so
# a consumer reaches it with a replace directive and imports CCXT unchanged.
cp "$src/go.mod" "$here/go.mod"
printf '%s\n' "$version" > "$here/UPSTREAM_VERSION"
printf '%s\n' "${keep[@]}" > "$here/EXCHANGES"

(cd "$here" && go build ./... && go vet ./ >/dev/null)
echo "trimmed CCXT $version to: ${keep[*]}"
